  t(cle: string, params?: Record<string, string | number>): string {
    const entree = this.dictionnaire[cle];
    let texte = entree ? entree[this.langue()] : cle;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        texte = texte.replace(new RegExp(String.raw`\{${k}\}`, 'g'), String(v));
      }
    }
    return texte;
  }

  basculer(): void {
    const nouvelle: Langue = this.langue() === 'fr' ? 'en' : 'fr';
    this.langue.set(nouvelle);
    localStorage.setItem('langue', nouvelle);
  }
